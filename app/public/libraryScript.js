// 字（{ b: 字母, v: 記号 } か { p: 'stop' | 'comma' }）の形の名。同じ名の字は同じ形。
export const shapeKey = (letter) => (letter.p ? letter.p : `${letter.b}.${letter.v}`);

// 字を x・基線 base・体の高さ size に置いた画の列（平らな px の点の並び・書き順どおり）と、字の送り。
export function placeLetter(letter, x, base, size) {
  const def = letter.p === 'stop' ? STOP : letter.p === 'comma' ? COMMA : BASES[letter.b];
  if (!def) throw new Error(`library script: unknown letter ${JSON.stringify(letter)}`);
  const to = ([u, v]) => [x + (u + (1 - v) * SLANT) * size, base - size + v * size];
  const strokes = def.strokes.map((stroke) => stroke.map(to));
  const mark = !letter.p && MARKS[letter.v];
  if (mark) for (const stroke of mark.at(def.wf)) strokes.push(stroke.map(to));
  return { strokes, advance: (def.wf + (mark ? mark.extra : 0)) * size };
}

// 語の幅（字の詰めを含み、最後の字の後ろの詰めも含む）。
export function wordWidth(word, size) {
  return word.reduce((sum, letter) => sum + placeLetter(letter, 0, 0, size).advance + LETTER_GAP * size, 0);
}

// 語彙と文の作り方（random は seeded）。nextWord(after) は、直前の字 after（無ければ null）と同じ形で始まらない語を返す。
export function createLanguage(random) {
  const pick = (weights) => {
    const total = weights.reduce((a, b) => a + b, 0);
    let r = random() * total;
    for (let i = 0; i < weights.length; i += 1) {
      r -= weights[i];
      if (r < 0) return i;
    }
    return weights.length - 1;
  };
  // 字母の頻度も偏らせる（順位に反比例を和らげたもの・順位は字母を混ぜた順）。母音は記号なしが多め。
  const order = BASES.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  const baseWeight = BASES.map((_, i) => 1 / (1 + order.indexOf(i)) ** 0.6);
  const markWeight = [0.3, 0.2, 0.18, 0.17, 0.15];
  const lengths = [0.14, 0.34, 0.3, 0.16, 0.06];
  const word = () => {
    const n = 1 + pick(lengths);
    const out = [];
    while (out.length < n) {
      const b = pick(baseWeight);
      if (out.length && out[out.length - 1].b === b) continue;
      out.push({ b, v: pick(markWeight) });
    }
    return out;
  };
  const lexicon = Array.from({ length: 48 }, word);
  const wordWeight = lexicon.map((_, k) => 1 / (k + 1));
  // 珍しい語（題・層の名前に使う、2 字以上の語）。
  const rare = lexicon.slice(20).filter((w) => w.length >= 2);
  const startsLike = (w, after) => after !== null && !after.p && shapeKey(after) === shapeKey(w[0]);
  const draw = (from, weights, after) => {
    for (;;) {
      const w = from[pick(weights)];
      if (!startsLike(w, after)) return w;
    }
  };
  return {
    nextWord: (after) => draw(lexicon, wordWeight, after),
    rareWord: (after) => draw(rare, rare.map(() => 1), after),
    sentenceLength: () => 4 + Math.floor(random() * 7),
    comma: () => random() < 0.22
  };
}
