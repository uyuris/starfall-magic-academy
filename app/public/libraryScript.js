// 円弧（渦）: 中心 (cx, cy)・半径 r0→r1・角度 a0→a1（度。0 が右・90 が下）。n は点の数。
function arc(cx, cy, r0, r1, a0, a1, n = 10) {
  const out = [];
  for (let i = 0; i <= n; i += 1) {
    const k = i / n;
    const a = ((a0 + (a1 - a0) * k) * Math.PI) / 180;
    const r = r0 + (r1 - r0) * k;
    out.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return out;
}
